#!/usr/bin/env -S uv run --script
# /// script
# requires-python = ">=3.10"
# dependencies = ["tad-dftd3==0.7.0", "tad-mctc==0.8.0", "torch", "numpy"]
#
# [tool.uv.sources]
# torch = { index = "pytorch-cpu" }
#
# [[tool.uv.index]]
# name = "pytorch-cpu"
# url = "https://download.pytorch.org/whl/cpu"
# explicit = true
# ///
"""Generate src/d3_data.cpp, the DFT-D3 reference tables pet-kokkos embeds.

Everything comes from tad-dftd3 0.7.0 and tad-mctc 0.8.0 (both Apache-2.0,
https://github.com/dftd3/tad-dftd3, https://github.com/tad-mctc/tad-mctc):

  reference C6 and reference coordination numbers   tad_dftd3/reference*.{py,pt}
  covalent radii (D3's, already scaled by 4/3)       tad_mctc.data.radii.COV_D3
  sqrt(<r4>/<r2>) expectation values                 tad_dftd3/data/r4r2.py
  pairwise van der Waals radii (zero damping, ATM)   tad_mctc.data.radii.VDW_PAIRWISE
  functional parameters and aliases                  tad_dftd3/param/{parameters,aliases}.toml

tad-dftd3 ships the C6 table as float32 and the pairwise radii as float32
bohr. Both were printed with four decimals (C6 in hartree bohr^6, radii in
Angstrom), so the original decimals are recovered exactly: C6 as the shortest
decimal that round-trips its float32 (every one has four decimals at most), the
radii as bohr x 0.529177210903 rounded to four decimals. Checked against
s-dftd3 1.7.0: energies agree to 1e-12 relative. Values with four decimals are
stored as integers x 10^4; dividing by 10^4 (correctly rounded) gives the double
nearest the decimal, which is what a decimal literal would give.

Run:  uv run tools/gen_d3_data.py > src/d3_data.cpp
"""

import os
import sys
import tomllib

import numpy as np
import torch
import tad_dftd3
import tad_mctc
from tad_dftd3 import data as d3data
from tad_dftd3.reference import Reference
from tad_mctc.data import radii

BOHR = 0.529177210903  # CODATA 2018, Angstrom: the constant the radii were divided by
MAXZ = 104             # 0 (a dummy) and 1..103


def dec4(x):
    k = int(round(float(x) * 1e4))
    assert k / 1e4 == float(x) or abs(k / 1e4 - float(x)) < 1e-12, x
    return k


def main():
    out = sys.stdout
    c6f = Reference(dtype=torch.float32).c6.numpy()
    c6 = np.vectorize(lambda x: float(str(np.float32(x))))(c6f)
    cnref = Reference(dtype=torch.float64).cn.numpy()
    nref = (cnref >= 0).sum(axis=1)
    rcov = radii.COV_D3(dtype=torch.float64).numpy()[:MAXZ]
    r4r2 = d3data.R4R2(dtype=torch.float64).numpy()[:MAXZ]
    rvdw = radii.VDW_PAIRWISE(dtype=torch.float64).numpy()
    r0 = np.round(rvdw * BOHR, 4)
    assert np.abs(rvdw * BOHR - r0).max() < 1e-6

    pdir = os.path.join(os.path.dirname(tad_dftd3.__file__), "param")
    with open(os.path.join(pdir, "parameters.toml"), "rb") as f:
        params = tomllib.load(f)
    with open(os.path.join(pdir, "aliases.toml"), "rb") as f:
        aliases = tomllib.load(f)["alias"]

    w = out.write
    w("// Generated by tools/gen_d3_data.py -- do not edit.\n")
    w("//\n")
    w(f"// DFT-D3 reference data from tad-dftd3 {tad_dftd3.__version__} and tad-mctc {tad_mctc.__version__}\n")
    w("// (Apache-2.0, https://github.com/dftd3/tad-dftd3, https://github.com/tad-mctc/tad-mctc;\n")
    w("// see NOTICE). The functional parameters are tad-dftd3's copy of s-dftd3's\n")
    w("// parameters.toml: published fits, with their DOIs below.\n")
    w('#include "d3_data.hpp"\n\nnamespace pet::d3data {\n\n')

    w("const int nref[kMaxZ] = {")
    w(", ".join(str(int(x)) for x in nref))
    w("};\n\n")

    w("// Reference coordination numbers x 10^4, kMaxRef per element (unused: -10^4).\n")
    w("const int cnref_e4[kMaxZ * kMaxRef] = {\n")
    for z in range(MAXZ):
        w("  " + ", ".join(str(dec4(x)) for x in cnref[z]) + ",\n")
    w("};\n\n")

    def doubles(name, arr, comment):
        w(f"// {comment}\nconst double {name}[kMaxZ] = {{\n")
        for k in range(0, MAXZ, 4):
            w("  " + ", ".join(repr(float(x)) for x in arr[k:k + 4]) + ",\n")
        w("};\n\n")

    doubles("rcov_bohr", rcov, "Covalent radii (bohr), Pyykko and Atsumi's scaled by 4/3, metals by a further 0.9.")
    doubles("r4r2_bohr", r4r2, "sqrt(0.5 <r^4>/<r^2> sqrt(Z)) (bohr): C8 = 3 C6 r4r2_i r4r2_j.")

    w("// Pairwise van der Waals radii x 10^4 (Angstrom), lower triangle: (i, j), i >= j >= 1,\n")
    w("// at i (i - 1) / 2 + j - 1.\n")
    w("const int r0_e4[kR0Pairs] = {\n")
    vals = [dec4(r0[i, j]) for i in range(1, MAXZ) for j in range(1, i + 1)]
    for k in range(0, len(vals), 12):
        w("  " + ", ".join(str(x) for x in vals[k:k + 12]) + ",\n")
    w("};\n\n")

    # C6: for each (i, j), i >= j, the nref[i] x nref[j] block [a][b], packed.
    w("// Reference C6 x 10^4 (hartree bohr^6). Pair (i, j), i >= j >= 1, is the block\n")
    w("// [a][b] (a: i's references, b: j's) at c6_off[i (i - 1) / 2 + j - 1].\n")
    offs, flat = [], []
    for i in range(1, MAXZ):
        for j in range(1, i + 1):
            offs.append(len(flat))
            for a in range(nref[i]):
                for b in range(nref[j]):
                    flat.append(dec4(c6[i, j, a, b]))
    w(f"const int c6_off[kR0Pairs] = {{\n")
    for k in range(0, len(offs), 12):
        w("  " + ", ".join(str(x) for x in offs[k:k + 12]) + ",\n")
    w("};\n")
    w(f"const int c6_e4[{len(flat)}] = {{\n")
    for k in range(0, len(flat), 12):
        w("  " + ", ".join(str(x) for x in flat[k:k + 12]) + ",\n")
    w("};\n")
    w(f"const int c6_count = {len(flat)};\n\n")

    # Functionals: BJ and zero parameters, defaults from [default.parameter].
    w("// Functional parameters: name, then BJ (s6, s8, a1, a2 in bohr) if any, then zero\n")
    w("// (s6, s8, rs6, rs8) if any. Missing s6 is 1, missing rs8 1, missing s8 0.\n")
    w("const Functional functionals[] = {\n")
    nan = "kNone"
    count = 0
    for name, entry in params["parameter"].items():
        d3 = entry.get("d3", {})
        bj, zero = d3.get("bj"), d3.get("zero")
        if not bj and not zero:
            continue
        def f(x):
            return repr(float(x))
        b = (f"true, {f(bj.get('s6', 1.0))}, {f(bj.get('s8', 0.0))}, {f(bj['a1'])}, {f(bj['a2'])}"
             if bj else f"false, 0, 0, 0, 0")
        z = (f"true, {f(zero.get('s6', 1.0))}, {f(zero.get('s8', 0.0))}, {f(zero['rs6'])}, {f(zero.get('rs8', 1.0))}"
             if zero else f"false, 0, 0, 0, 0")
        doi = (bj or {}).get("doi") or (zero or {}).get("doi") or ""
        w(f'  {{"{name}", {b}, {z}}},  // {doi}\n')
        count += 1
    w("};\n")
    w(f"const int n_functionals = {count};\n\n")
    w("const Alias aliases[] = {\n")
    for a, t in aliases.items():
        w(f'  {{"{a}", "{t}"}},\n')
    w("};\n")
    w(f"const int n_aliases = {len(aliases)};\n\n")
    w("}  // namespace pet::d3data\n")


if __name__ == "__main__":
    main()
